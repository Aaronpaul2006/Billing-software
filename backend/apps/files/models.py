from django.db import models
from django.db.models import Q

from apps.core.db import (
    created_at,
    length_between,
    one_of,
    ref,
    tenant_id_key,
    tenant_ref,
    uuid7_pk,
)

MAX_ATTACHMENT_BYTES = 20 * 1024 * 1024


class AttachmentStatus(models.TextChoices):
    PENDING = "PENDING"
    AVAILABLE = "AVAILABLE"
    QUARANTINED = "QUARANTINED"


class AttachmentContentType(models.TextChoices):
    PDF = "application/pdf"
    JPEG = "image/jpeg"
    PNG = "image/png"
    WEBP = "image/webp"


class Attachment(models.Model):
    """Metadata of a file in object storage. The storage key is generated by
    the server, never taken from the client."""

    ContentType = AttachmentContentType
    Status = AttachmentStatus
    id = uuid7_pk()
    tenant = tenant_ref()
    storage_key = models.TextField()
    original_filename = models.TextField()
    content_type = models.TextField(choices=ContentType)
    size_bytes = models.BigIntegerField()
    sha256 = models.BinaryField(null=True)
    status = models.TextField(
        choices=Status, default=AttachmentStatus.PENDING, db_default=AttachmentStatus.PENDING
    )
    uploaded_by = ref("accounts.User", db_column="uploaded_by")
    created_at = created_at()

    class Meta:
        db_table = "attachments"
        constraints = [
            tenant_id_key("attachments"),
            models.UniqueConstraint(fields=["storage_key"], name="attachments_storage_key_key"),
            length_between("original_filename", 1, 255, "attachments_original_filename_check"),
            one_of("content_type", AttachmentContentType.values, "attachments_content_type_check"),
            models.CheckConstraint(
                condition=Q(size_bytes__gt=0) & Q(size_bytes__lte=MAX_ATTACHMENT_BYTES),
                name="attachments_size_bytes_check",
            ),
            models.CheckConstraint(
                condition=Q(sha256__octet_length=32), name="attachments_sha256_check"
            ),
            one_of("status", AttachmentStatus.values, "attachments_status_check"),
        ]
