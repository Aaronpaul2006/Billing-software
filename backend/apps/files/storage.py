"""Object storage (S3 API): SeaweedFS locally, AWS S3 / Cloudflare R2 in production.

Files never pass through or live on the app server's disk; downloads use
short-lived presigned URLs (docs/01-architecture.md §6, Files). Keys are
generated by the server, never taken from the client.
"""

import uuid
from dataclasses import dataclass
from functools import cache
from typing import Any
from urllib.parse import quote

import boto3
from botocore.config import Config
from botocore.exceptions import ClientError
from django.conf import settings

DOWNLOAD_URL_TTL = 300  # seconds


@cache
def _client(endpoint: str | None) -> Any:
    return boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=settings.S3_ACCESS_KEY,
        aws_secret_access_key=settings.S3_SECRET_KEY,
        region_name=settings.S3_REGION,
        config=Config(signature_version="s3v4", s3={"addressing_style": "path"}),
    )


def internal_client() -> Any:
    """For uploads from the API / worker (inside the network)."""
    return _client(settings.S3_ENDPOINT_URL)


def public_client() -> Any:
    """For presigning: the URL must be reachable by the user's browser."""
    return _client(settings.S3_PUBLIC_ENDPOINT_URL or settings.S3_ENDPOINT_URL)


def new_key(tenant_id: uuid.UUID, kind: str, filename: str) -> str:
    """tenants/<tenant>/<kind>/<uuid7>/<filename>: unguessable, tenant-prefixed."""
    return f"tenants/{tenant_id}/{kind}/{uuid.uuid7()}/{filename}"


def put(key: str, body: bytes, content_type: str) -> None:
    internal_client().put_object(
        Bucket=settings.S3_BUCKET, Key=key, Body=body, ContentType=content_type
    )


def get(key: str) -> bytes:
    response = internal_client().get_object(Bucket=settings.S3_BUCKET, Key=key)
    data: bytes = response["Body"].read()
    return data


def content_disposition(filename: str, disposition: str = "inline") -> str:
    """The name made safe for a header: an ASCII fallback without quotes or
    control characters, plus the exact name in RFC 6266 / 5987 form."""
    fallback = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "_" for c in filename)
    return f"{disposition}; filename=\"{fallback}\"; filename*=UTF-8''{quote(filename, safe='')}"


def download_url(
    key: str, filename: str, ttl: int = DOWNLOAD_URL_TTL, disposition: str = "inline"
) -> str:
    url: str = public_client().generate_presigned_url(
        "get_object",
        Params={
            "Bucket": settings.S3_BUCKET,
            "Key": key,
            "ResponseContentDisposition": content_disposition(filename, disposition),
        },
        ExpiresIn=ttl,
    )
    return url


def upload_url(key: str, content_type: str, size: int) -> tuple[str, dict[str, str]]:
    """A presigned PUT that only accepts exactly this type and size: both are
    signed headers, so storage refuses any other (403 SignatureDoesNotMatch).
    Returns the URL and the headers the client must send."""
    url: str = public_client().generate_presigned_url(
        "put_object",
        Params={
            "Bucket": settings.S3_BUCKET,
            "Key": key,
            "ContentType": content_type,
            "ContentLength": size,
        },
        ExpiresIn=settings.UPLOAD_URL_TTL,
    )
    return url, {"Content-Type": content_type}  # browsers set Content-Length themselves


@dataclass(frozen=True)
class StoredObject:
    size: int
    content_type: str


def head(key: str) -> StoredObject | None:
    """The object's size and type, or None if nothing was uploaded under `key`."""
    try:
        meta = internal_client().head_object(Bucket=settings.S3_BUCKET, Key=key)
    except ClientError as exc:
        if exc.response.get("Error", {}).get("Code") in {"404", "NoSuchKey", "NotFound"}:
            return None
        raise
    return StoredObject(size=int(meta["ContentLength"]), content_type=str(meta["ContentType"]))


def get_range(key: str, length: int) -> bytes:
    response = internal_client().get_object(
        Bucket=settings.S3_BUCKET, Key=key, Range=f"bytes=0-{length - 1}"
    )
    data: bytes = response["Body"].read()
    return data


def delete(key: str) -> None:
    internal_client().delete_object(Bucket=settings.S3_BUCKET, Key=key)
